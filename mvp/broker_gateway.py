from typing import Callable, ContextManager, Protocol


class SandboxGateway(Protocol):
    def accounts(self) -> list[dict]: ...
    def open_account(self, name: str) -> str: ...
    def pay_in(self, account_id: str, amount: float) -> dict: ...
    def snapshot(self, account_id: str) -> dict: ...
    def catalog(self) -> list[dict]: ...
    def preview_order(self, account_id: str, instrument_uid: str, lots: int,
                      limit_price: float, direction: str = "buy", quote_policy: str = "strict_30s") -> dict: ...
    def place_order(self, account_id: str, plan: dict, order_id: str,
                    before_send: Callable[[], ContextManager] | None = None) -> dict: ...
    def order_state(self, account_id: str, order_id: str, request: bool = True) -> dict: ...
    def cancel_order(self, account_id: str, order_id: str, request: bool = False) -> dict: ...
